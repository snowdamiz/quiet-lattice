/** Real names the filter refuses, and why: a blocked word that repeated letters collapse into, and two separators in a row. */
const KNOWN_REFUSED = [
  ['Twatt', 'blocked'],
  ["John o' Groats", 'characters'],
] as const;

const generated = (() => {
  const names: string[] = [];
  for (const sys of new Galaxy(424242).systems) {
    const d = describeGalaxySystem(sys);
    names.push(d.name, ...d.bodies.map((b) => b.name));
  }
  return [...new Set(names)];
})();

describe('the name filter does not refuse real or generated names', () => {
  it('takes English and European place names, and ones the game would use', () => {
    const real = [...ENGLISH, ...EUROPE, ...GAME];
    expect(new Set(real).size).toBeGreaterThanOrEqual(200);
    const refused = real.map((n) => [n, reason(n)] as const).filter(([, r]) => r !== null);
    expect(refused).toEqual([]);
  });

  it('refuses the real names it is known to refuse, each for its reason', () => {
    for (const [name, why] of KNOWN_REFUSED) expect(reason(name), name).toBe(why);
  });

  it('takes the systems and worlds generated for seed 424242', () => {
    expect(generated.length).toBeGreaterThanOrEqual(200);
    const refused = generated.map((n) => [n, reason(n)] as const).filter(([, r]) => r !== null);
    expect(refused).toEqual([]);
  });

  it('takes the reserved names as a moderator’s renames, and refuses them from a finder', () => {
    const reserved = [...PEOPLES.flatMap((p) => [p.name, p.capital.name]), ...FACTIONS.map((f) => f.name)];
    expect(reserved.length).toBeGreaterThan(10);
    for (const n of reserved) {
      expect(reason(n, { reserved: false }), n).toBeNull();
      expect(reason(n), n).toBe('reserved');
    }
  });
});
