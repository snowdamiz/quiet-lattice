// Bosses (DESIGN 13), phases in order. Base health and damage are this table's choices (before level and party scaling),
// recorded in docs/DECISIONS.md. Raids and events scale to 1–12 players (DESIGN 16.6).
import { z } from 'zod';
import { chapterSchema, hullIdSchema, idSchema, lookup, table, tierRangeSchema, worldTypeSchema, LIVING_WORLDS } from './common.ts';
import { bodyPlanIdSchema, counterSchema, resistanceSchema, HOLLOW_RESISTANCES, SENTINEL_RESISTANCES } from './mobs.ts';
import { resourceIdSchema } from './resources.ts';

export const bossSchema = z.strictObject({
  id: idSchema,
  name: z.string().min(1),
  where: z.string().min(1),
  worlds: z.array(worldTypeSchema).min(1).optional(),
  chapters: z.array(chapterSchema).optional(),
  tier: tierRangeSchema,
  kind: z.enum(['world_boss', 'mini_boss', 'dungeon', 'dungeon_boss', 'space_boss', 'raid']),
  /** Who it is built for, as DESIGN's kind column says it. */
  party: z.string().min(1).nullable(),
  /** False for the Descent: the Patient is not a kill. */
  killable: z.boolean(),
  /** Damage on Wardens and the Hive Heart persists for the week (DESIGN 16.6). */
  persistent: z.boolean(),
  bodyPlan: bodyPlanIdSchema.nullable(),
  hull: hullIdSchema.nullable(),
  /** Mob archetypes or temperaments that fight with it or make up its arena. */
  mobs: z.array(idSchema),
  /** Skill nodes it casts. */
  uses: z.array(idSchema),
  baseHealth: z.number().positive().nullable(),
  baseDamage: z.number().positive().nullable(),
  phases: z
    .array(
      z.strictObject({
        name: z.string().min(1),
        text: z.string().min(1),
        healthBelow: z.number().gt(0).lt(1).optional(),
        intervalS: z.number().positive().optional(),
      }),
    )
    .min(1),
  counter: counterSchema,
  resistances: z.array(resistanceSchema),
  /** The ×3 bosses and the lesser Wardens. */
  variants: z.array(
    z.strictObject({ id: idSchema, name: z.string().min(1), where: z.string().min(1), world: worldTypeSchema.optional(), text: z.string().min(1).optional() }),
  ),
  loot: z.strictObject({ items: z.array(idSchema), recipes: z.array(idSchema), resources: z.array(resourceIdSchema) }),
});
export type Boss = z.infer<typeof bossSchema>;

