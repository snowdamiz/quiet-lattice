// The hull roster (DESIGN 10.2). Today's ship is the Lark: 600/240 speed, boost ×2.6, hull, shield and Charge 100, signature 1.0.
import { z } from 'zod';
import { capitalIdSchema, factionIdSchema, hullIdSchema, idSchema, lookup, peopleIdSchema, table, weaponSizeSchema } from './common.ts';
import { statModSchema } from './modifiers.ts';

export const hullVenueSchema = z.discriminatedUnion('kind', [
  z.strictObject({ kind: z.literal('waystation') }),
  z.strictObject({ kind: z.literal('capital'), capital: capitalIdSchema }),
  z.strictObject({ kind: z.literal('faction'), faction: factionIdSchema, vendor: z.string().min(1) }),
  z.strictObject({ kind: z.literal('quest'), quest: idSchema }),
  z.strictObject({ kind: z.literal('drop'), source: z.string().min(1) }),
  z.strictObject({ kind: z.literal('craft'), recipe: idSchema }),
]);
export type HullVenue = z.infer<typeof hullVenueSchema>;

export const hullSchema = z.strictObject({
  id: hullIdSchema,
  name: z.string().min(1),
  /** 0–3, or 'end' for the endgame Husk. */
  tier: z.union([z.int().min(0).max(3), z.literal('end')]),
  role: z.string().min(1),
  speed: z.strictObject({ space: z.number().positive(), atmo: z.number().positive() }),
  boost: z.number().positive(),
  hull: z.number().positive(),
  shield: z.number().nonnegative(),
  /** Charge capacity, or 'count' for the Husk, which draws its Charge from the Count. */
  charge: z.union([z.number().positive(), z.literal('count')]),
  cargoPods: z.int().nonnegative(),
  /** Detection multiplier (1.0 = today's ship); the Husk reads differently to the Hollow. */
  signature: z.strictObject({ base: z.number().positive(), vsHollow: z.number().positive().optional() }),
  hardpoints: z.array(weaponSizeSchema).min(1),
  abilitySlots: z.int().positive(),
  sold: z.array(hullVenueSchema).min(1),
  price: z.strictObject({
    /** Units, or null where the hull is not bought for units (the staked Lark, the raid-only Husk). */
    units: z.int().positive().nullable(),
    credit: z.boolean(),
    rep: z.strictObject({ faction: factionIdSchema, rank: idSchema }).nullable(),
    raid: z.boolean(),
  }),
  /** Skill nodes the hull carries whether or not the pilot owns them, plus stat perks and plain flags. */
  builtIn: z.strictObject({ nodes: z.array(idSchema), mods: z.array(statModSchema), flags: z.array(idSchema) }),
  /** The people whose capital yard builds this line, if any (DESIGN 10.2, 10.4). */
  people: peopleIdSchema.nullable(),
});
export type Hull = z.infer<typeof hullSchema>;

